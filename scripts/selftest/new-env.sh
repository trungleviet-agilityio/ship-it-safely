#!/usr/bin/env bash
# Self-tests of the environment clone script (tf/new-env.sh, ADR 0008 P2, tests T1 to T14) and of the environment parity
# guard (guard/env-parity.sh, P3). Each case runs in a throwaway git repository that holds copies of lib.sh, the script
# and the real envs/dev root, so nothing touches this checkout. Run by scripts/ci/selftest.sh; also runnable alone.

# shellcheck source=scripts/selftest/common.sh
source "$(dirname "$0")/common.sh"

real_dev="$ROOT/infra/terraform/envs/dev"
[ -d "$real_dev" ] || die "selftest: infra/terraform/envs/dev is missing"

# mk_repo <dir>: a fixture repository (index only, no commit): the script, lib.sh, the real dev root and example, the
# real .gitignore and the two workflows the parity guard reads. Local files (.terraform/, auto.tfvars, state, a plan)
# are added to the source on purpose: they are ignored, so the clone must not copy them.
mk_repo() {
  local r="$1"
  mkdir -p "$r/scripts/tf" "$r/infra/terraform/bootstrap/accounts" "$r/infra/terraform/envs" "$r/.github/workflows"
  cp "$ROOT/scripts/lib.sh" "$r/scripts/lib.sh"
  cp "$ROOT/scripts/tf/new-env.sh" "$r/scripts/tf/new-env.sh"
  cp -R "$real_dev" "$r/infra/terraform/envs/dev"
  rm -rf "$r/infra/terraform/envs/dev/.terraform"
  cp "$ROOT/infra/terraform/bootstrap/accounts/dev.tfvars.example" "$r/infra/terraform/bootstrap/accounts/"
  cp "$ROOT/.gitignore" "$r/.gitignore"
  cp "$ROOT/.github/workflows/terraform-iac.yml" "$ROOT/.github/workflows/terraform-destroy.yml" "$r/.github/workflows/"
  git init -q "$r" 2>/dev/null
  git -C "$r" add -A
  mkdir -p "$r/infra/terraform/envs/dev/.terraform"
  : >"$r/infra/terraform/envs/dev/.terraform/provider"
  : >"$r/infra/terraform/envs/dev/local.auto.tfvars"
  : >"$r/infra/terraform/envs/dev/terraform.tfstate"
  : >"$r/infra/terraform/envs/dev/tfplan"
}
# tree_hash <dir>: one hash of every file (the .git directory excluded), to prove nothing changed.
tree_hash() {
  local f
  (cd "$1" && find . -type f -not -path './.git/*' | sort) | while IFS= read -r f; do printf '%s %s\n' "$f" "$(sha256_of "$1/$f")"; done | sha256_of /dev/stdin
}
# sedi <expression> <file>: portable in-place edit.
sedi() {
  sed "$1" "$2" >"$2.new"
  mv "$2.new" "$2"
}
# ne <label> <expected text> <command...>: the command must exit 1 or 2 and its output must hold the text.
ne() {
  local label="$1" text="$2" out rc=0
  shift 2
  out="$(
    trap - ERR
    "$@" 2>&1
  )" || rc=$?
  { [ "$rc" -eq 1 ] || [ "$rc" -eq 2 ]; } || die "selftest: ${label} should exit 1 or 2, got ${rc}: ${out}"
  case "$out" in *"$text"*) ok "${label} is refused" ;; *) die "selftest: ${label} was refused without '${text}': ${out}" ;; esac
}

# --- T1 qa from dev: the files, the rewrites, nothing local copied
r="$tmp/t1"
mk_repo "$r"
# With a remote the printed commands name the repository, so they are runnable as printed (no <OWNER>/<REPO> placeholder).
git -C "$r" remote add origin https://github.com/octo/repo.git
new_env="$r/scripts/tf/new-env.sh"
out="$("$new_env" qa --from dev 2>&1)" || die "selftest: new-env qa failed: $out"
qa="$r/infra/terraform/envs/qa" accounts="$r/infra/terraform/bootstrap/accounts"
[ -f "$qa/.terraform.lock.hcl" ] || die "selftest: the clone must carry the lock file"
{ [ ! -e "$qa/.terraform" ] && [ ! -e "$qa/local.auto.tfvars" ] && [ ! -e "$qa/terraform.tfstate" ] && [ ! -e "$qa/tfplan" ]; } \
  || die "selftest: the clone copied a local file"
changed="$({ diff -rq -x .terraform -x '*.auto.tfvars' -x '*.tfstate' -x tfplan "$r/infra/terraform/envs/dev" "$qa" || true; } | sed -E 's#.* and .*/(.*) differ#\1#' | sort | tr '\n' ' ')"
[ "$changed" = "backend.tf terraform.tfvars " ] || die "selftest: the clone differs from dev in: $changed"
stray="$(diff "$r/infra/terraform/envs/dev/terraform.tfvars" "$qa/terraform.tfvars" | grep -E '^[<>]' | grep -Ev '^[<>] (env |vpc_cidr |#)' || true)"
[ -z "$stray" ] || die "selftest: terraform.tfvars changed outside env, vpc_cidr and the header: $stray"
stray="$(diff "$r/infra/terraform/envs/dev/backend.tf" "$qa/backend.tf" | grep -E '^[<>]' | grep -Ev '^[<>]\s+key ' || true)"
[ -z "$stray" ] || die "selftest: backend.tf changed outside the key line: $stray"
head -n1 "$qa/terraform.tfvars" | grep -q 'Generated by scripts/tf/new-env.sh from envs/dev' || die "selftest: the clone tfvars has no generated header"
grep -Eq '^env +=[ ]+"qa"$' "$qa/terraform.tfvars" || die "selftest: env was not rewritten"
grep -Eq '^vpc_cidr +=[ ]+"10\.50\.0\.0/16"$' "$qa/terraform.tfvars" || die "selftest: vpc_cidr was not the next free /16"
grep -q 'key          = "envs/qa/terraform.tfstate"' "$qa/backend.tf" || die "selftest: the backend key was not rewritten"
grep -q '<QA_ACCOUNT_ID>' "$accounts/qa.tfvars.example" || die "selftest: the example placeholders were not renamed"
! grep -q 'DEV_ACCOUNT_ID' "$accounts/qa.tfvars.example" || die "selftest: the example still holds the source placeholder"
grep -q "^env = \"qa\"" "$accounts/qa.tfvars.example" || die "selftest: the example must set env (the bootstrap default is dev)"
head -n1 "$accounts/qa.tfvars.example" | grep -q 'Copy to qa.tfvars' || die "selftest: the example header was not renamed"
[ -n "$(find "$accounts/qa.tfvars" -perm 600 -type f)" ] || die "selftest: qa.tfvars must be mode 600"
git -C "$r" check-ignore -q -- infra/terraform/bootstrap/accounts/qa.tfvars || die "selftest: qa.tfvars must be gitignored"
! git -C "$r" check-ignore -q -- infra/terraform/bootstrap/accounts/qa.tfvars.example || die "selftest: qa.tfvars.example must not be ignored"
[ "$(find "$r/infra/terraform/envs" -mindepth 1 -maxdepth 1 -exec basename {} \; | sort | tr '\n' ' ')" = "dev qa " ] || die "selftest: unexpected entries under envs/ (a temp directory left behind?)"
ok "new-env: qa clone holds the tracked files, rewrites only the named keys, copies no local file"

# --- T13 output scan (the T1 output)
case "$out" in *"<ENV_ACCOUNT_ID>"*"plan-qa:"*"reusable-terraform-plan.yml"*) ;; *) die "selftest: the next steps lack the placeholder or the plan caller snippet" ;; esac
! grep -Eq "$ACCOUNT_ID_DIGITS" <<<"$out" || die "selftest: new-env printed a 12-digit run"
ok "new-env: the output has the YAML snippet and a placeholder, and no 12-digit run"
# Every printed command (the lines indented by five spaces) must work when pasted into a shell as printed: no heredoc
# (an indented terminator never ends it, so the paste hangs) and no here-string, and the block must parse.
printf '%s\n' "$out" >"$tmp/next-steps.txt"
grep -E '^     [^ ]' "$tmp/next-steps.txt" >"$tmp/commands.sh" || die "selftest: the next steps print no command lines"
! grep -nE '<<|^[[:space:]]+(JSON|EOF)$' "$tmp/commands.sh" || die "selftest: a printed command uses a heredoc or here-string (it hangs when pasted)"
bash -n "$tmp/commands.sh" || die "selftest: the printed commands do not parse as shell"
if command -v zsh >/dev/null 2>&1; then zsh -n "$tmp/commands.sh" || die "selftest: the printed commands do not parse in zsh"; fi
# The environment-creation call sends valid JSON built by the printed printf (the id is a stand-in here).
env_payload="$(grep -F 'printf '"'"'{"reviewers"' "$tmp/commands.sh" | sed -E 's/ \| gh api.*$//')"
[ -n "$env_payload" ] || die "selftest: the next steps lack the environment payload command"
MY_ID=42 bash -c "$env_payload" | jq -e '.reviewers[0].id == 42 and .deployment_branch_policy.custom_branch_policies == true' >/dev/null \
  || die "selftest: the printed environment payload is not the expected JSON"
# The printed caller job is the real plan-dev job with the environment renamed, so a change to one cannot drift from the
# other; its `uses:` line carries the zizmor ignore too (comments are not in the parsed YAML).
"$(ci_python)" -I - "$tmp/next-steps.txt" "$ROOT/.github/workflows/terraform-iac.yml" <<'PY' || die "selftest: the printed plan-qa job differs from plan-dev"
import re
import sys
import textwrap

import yaml

printed = open(sys.argv[1]).read()
real_text = open(sys.argv[2]).read()
block = re.search(r"^        plan-qa:\n(.*?)(?=^   b\. )", printed, re.S | re.M)
if not block:
    sys.exit("no plan-qa snippet in the next steps")
snippet = textwrap.dedent("        plan-qa:\n" + block.group(1))
job = yaml.safe_load(snippet)["plan-qa"]


def rename(node):
    if isinstance(node, dict):
        return {k: rename(v) for k, v in node.items()}
    if isinstance(node, str):
        return "qa" if node == "dev" else node.replace("plan-dev", "plan-qa").replace("(dev)", "(qa)").replace("_DEV", "_QA")
    return node


expected = rename(yaml.safe_load(real_text)["jobs"]["plan-dev"])
if job != expected:
    sys.exit(f"printed job {job}\nexpected    {expected}")
uses = [ln.strip() for ln in snippet.splitlines() if ln.strip().startswith("uses:")]
real_uses = [ln.strip() for ln in real_text.splitlines() if ln.strip().startswith("uses: ./.github/workflows/reusable-")]
if uses != real_uses or "# zizmor: ignore[self-repository]" not in uses[0]:
    sys.exit(f"the uses line differs: {uses} vs {real_uses}")
PY
ok "new-env: the printed commands are pasteable and the printed caller job equals plan-dev"

# --- T2 run again: refused, files unchanged
before="$(tree_hash "$r")"
ne "a second run" "already exists" "$new_env" qa
for p in infra/terraform/envs/qa infra/terraform/bootstrap/accounts/qa.tfvars.example infra/terraform/bootstrap/accounts/qa.tfvars; do
  out="$("$new_env" qa 2>&1 || true)"
  case "$out" in *"$p"*) ;; *) die "selftest: the refusal does not list $p" ;; esac
done
[ "$(tree_hash "$r")" = "$before" ] || die "selftest: a refused second run changed files"

# --- T5 the next free CIDR with dev at 10.40 and qa at 10.50
out="$("$new_env" pr --dry-run 2>&1)" || die "selftest: dry run failed: $out"
case "$out" in *'vpc_cidr = "10.60.0.0/16"'*) ok "new-env: the next CIDR follows the highest used one" ;; *) die "selftest: expected 10.60: $out" ;; esac

# --- T3 bad names, T4 bad --from, T6 bad CIDRs, strategy: all refused, nothing written
for bad in Dev a toolongname ../x "dev prod" bootstrap local shared env "$(printf 'qa\n../x')"; do
  ne "name '${bad//$'\n'/ NEWLINE }'" "env" "$new_env" "$bad"
done
ne "an empty name" "usage:" "$new_env" ""
ne "no arguments" "usage:" "$new_env"
ne "--from without a value" "usage:" "$new_env" pr --from
ne "an unknown flag" "usage:" "$new_env" pr --force
ne "--from itself" "must differ" "$new_env" pr --from pr
ne "--from a missing root" "does not exist" "$new_env" pr --from nosuch
for bad in 10.40.0.0/16 10.50.0.0/16 10.1.0.0/24 192.168.0.0/16 garbage 10.300.0.0/16 10.01.0.0/16; do
  ne "--cidr $bad" "--cidr" "$new_env" pr --cidr "$bad"
done
"$new_env" pr --cidr 10.70.0.0/16 --dry-run >/dev/null 2>&1 || die "selftest: a free --cidr was refused"
ne "--strategy without the key in the source" "deployment_strategy" "$new_env" pr --strategy BLUE_GREEN
ne "--strategy with a bad value" "--strategy must be" "$new_env" pr --strategy CANARY
[ "$(tree_hash "$r")" = "$before" ] || die "selftest: a refused run wrote files"

# --- T9 dry run writes nothing
"$new_env" pr --dry-run >/dev/null 2>&1 || die "selftest: dry run failed"
[ "$(tree_hash "$r")" = "$before" ] || die "selftest: --dry-run wrote files"
ok "new-env: a dry run writes nothing"

# --- --strategy and promotion_target_env: rewritten only when the source has the keys
r="$tmp/strategy"
mk_repo "$r"
printf 'deployment_strategy  = "ROLLING"\npromotion_target_env = "prod"\n' >>"$r/infra/terraform/envs/dev/terraform.tfvars"
"$r/scripts/tf/new-env.sh" qa --strategy BLUE_GREEN >/dev/null 2>&1 || die "selftest: new-env with --strategy failed"
grep -Eq '^deployment_strategy +=[ ]+"BLUE_GREEN"$' "$r/infra/terraform/envs/qa/terraform.tfvars" || die "selftest: deployment_strategy was not rewritten"
grep -Eq '^promotion_target_env +=[ ]+""$' "$r/infra/terraform/envs/qa/terraform.tfvars" || die "selftest: promotion_target_env must be reset to empty in a clone"
grep -q 'promotion_target_env = "prod"' "$r/infra/terraform/envs/dev/terraform.tfvars" || die "selftest: the source tfvars was changed"
ok "new-env: --strategy and the promotion reset apply when the source has the keys"

# --- T7 source format changed
r="$tmp/t7"
mk_repo "$r"
printf 'env = "x"\n' >>"$r/infra/terraform/envs/dev/terraform.tfvars"
ne "a source with env twice" "source format changed" "$r/scripts/tf/new-env.sh" qa
r="$tmp/t7b"
mk_repo "$r"
sedi '/^vpc_cidr/d' "$r/infra/terraform/envs/dev/terraform.tfvars"
ne "a source without vpc_cidr" "source format changed" "$r/scripts/tf/new-env.sh" qa

# --- T8 account IDs in the source
r="$tmp/t8"
mk_repo "$r"
printf 'aws_account_id = "x"\n' >>"$r/infra/terraform/envs/dev/terraform.tfvars"
ne "a source with aws_account_id" "aws_account_id" "$r/scripts/tf/new-env.sh" qa
r="$tmp/t8b"
mk_repo "$r"
printf '# %s\n' "$leak_id" >>"$r/infra/terraform/envs/dev/terraform.tfvars"
ne "a source with a 12-digit run" "12-digit" "$r/scripts/tf/new-env.sh" qa

# --- T10 terraform, aws and gh are never called; T11 no cwd dependence
r="$tmp/t10"
mk_repo "$r"
mkdir -p "$tmp/failstubs"
for c in terraform aws gh; do
  printf '#!/bin/sh\necho "%s called" >>"%s/called"\nexit 1\n' "$c" "$tmp/failstubs" >"$tmp/failstubs/$c"
  chmod +x "$tmp/failstubs/$c"
done
(cd / && env PATH="$tmp/failstubs:$PATH" "$r/scripts/tf/new-env.sh" qa >/dev/null 2>&1) || die "selftest: new-env failed when run from / with failing stubs"
[ ! -e "$tmp/failstubs/called" ] || die "selftest: new-env called $(cat "$tmp/failstubs/called")"
[ -d "$r/infra/terraform/envs/qa" ] || die "selftest: running from / did not create the root"
ok "new-env: works from any directory and never calls terraform, aws or gh"

# --- T12 a target directory that is not writable mid-run: exit 1, nothing left behind
if [ "$(id -u)" -ne 0 ]; then
  r="$tmp/t12"
  mk_repo "$r"
  chmod a-w "$r/infra/terraform/bootstrap/accounts"
  ne "an unwritable accounts directory" "cannot create" "$r/scripts/tf/new-env.sh" qa
  chmod u+w "$r/infra/terraform/bootstrap/accounts"
  [ "$(ls -A "$r/infra/terraform/envs")" = "dev" ] || die "selftest: a failed run left $(ls -A "$r/infra/terraform/envs")"
  [ "$(ls -A "$r/infra/terraform/bootstrap/accounts")" = "dev.tfvars.example" ] || die "selftest: a failed run left account files"
  ok "new-env: a write failure leaves no target and no temp file"
else
  warn "running as root: skipping the unwritable-directory case (T12)"
fi

# --- T12b a later move fails (a stub mv refuses one target): everything already moved in is rolled back
mkdir -p "$tmp/mvstub"
# shellcheck disable=SC2016  # the stub's own script text, not an expansion here
printf '#!/bin/sh\nfor last; do :; done\ncase "$last" in *"$MV_FAIL_SUFFIX") exit 1 ;; esac\nexec /bin/mv "$@"\n' >"$tmp/mvstub/mv"
chmod +x "$tmp/mvstub/mv"
for fail_on in "/qa" "qa.tfvars.example" "qa.tfvars"; do
  r="$tmp/t12b"
  rm -rf "$r"
  mk_repo "$r"
  ne "a failing move of ${fail_on}" "cannot create" env PATH="$tmp/mvstub:$PATH" MV_FAIL_SUFFIX="$fail_on" "$r/scripts/tf/new-env.sh" qa
  [ "$(ls -A "$r/infra/terraform/envs")" = "dev" ] || die "selftest: a failed move of ${fail_on} left $(ls -A "$r/infra/terraform/envs") under envs/"
  [ "$(ls -A "$r/infra/terraform/bootstrap/accounts")" = "dev.tfvars.example" ] || die "selftest: a failed move of ${fail_on} left account files: $(ls -A "$r/infra/terraform/bootstrap/accounts")"
done
ok "new-env: a failing move rolls back the targets already moved in"

# --- T14 the account file must be ignored
r="$tmp/t14"
mk_repo "$r"
: >"$r/.gitignore"
before="$(tree_hash "$r")"
ne "an account file that is not ignored" "not gitignored" "$r/scripts/tf/new-env.sh" qa
[ "$(tree_hash "$r")" = "$before" ] || die "selftest: a refusal before writing still wrote files"

# --- Parity guard (P3). The base has a clone made by the script and the workflow lists extended by qa.
parity_base() {
  local p="$1"
  mk_repo "$p"
  "$p/scripts/tf/new-env.sh" qa >/dev/null 2>&1 || die "selftest: could not clone qa for the parity fixtures"
  python3 -I - "$p/.github/workflows" <<'PY'
import re
import sys

wf = sys.argv[1]
text = open(f"{wf}/terraform-iac.yml").read()
text = text.replace("options: [dev]", "options: [dev, qa]")
block = re.search(r"  plan-dev:\n.*?(?=\n  apply:)", text, re.S).group(0)
text = text.replace(block, block + "\n" + block.replace("plan-dev", "plan-qa").replace("(dev)", "(qa)").replace("env: dev", "env: qa").replace("_DEV", "_QA"))
open(f"{wf}/terraform-iac.yml", "w").write(text)
text = open(f"{wf}/terraform-destroy.yml").read()
text = text.replace("options: [dev]", "options: [dev, qa]").replace('allowed_envs="dev"', 'allowed_envs="dev qa"')
open(f"{wf}/terraform-destroy.yml", "w").write(text)
PY
}
parity() { "$ROOT/scripts/guard/env-parity.sh" "$1"; }
base="$tmp/parity"
parity_base "$base"
parity "$base" >/dev/null 2>&1 || die "selftest: the parity guard rejected a fresh clone"
# parity_case <label> <expected text> <sed expression> <file under the copy>: copy the base, edit one file, expect the failure.
parity_case() {
  local p="$tmp/pc-$RANDOM"
  cp -R "$base" "$p"
  sedi "$3" "$p/$4"
  cmp -s "$base/$4" "$p/$4" && die "selftest: could not mutate $4 for '$1'"
  expect_fail "parity: $1" "$2" "$ROOT/scripts/guard/env-parity.sh" "$p"
  rm -rf "$p"
}
parity_case "a missing dispatch choice" "missing from the terraform-iac.yml dispatch choice" 's/options: \[dev, qa\]/options: [dev]/' .github/workflows/terraform-iac.yml
parity_case "an extra dispatch choice" "lists 'zz'" 's/options: \[dev, qa\]/options: [dev, qa, zz]/' .github/workflows/terraform-iac.yml
parity_case "a missing destroy choice" "missing from the terraform-destroy.yml dispatch choice" 's/options: \[dev, qa\]/options: [dev]/' .github/workflows/terraform-destroy.yml
parity_case "a missing destroy allowed_envs entry" "missing from the terraform-destroy.yml allowed_envs" 's/allowed_envs="dev qa"/allowed_envs="dev"/' .github/workflows/terraform-destroy.yml
parity_case "a caller job named wrongly" "must be named plan-qa" 's/^  plan-qa:/  plan-qa2:/' .github/workflows/terraform-iac.yml
parity_case "a caller job for another env" "no plan-qa caller job" 's/^      env: qa$/      env: zz/' .github/workflows/terraform-iac.yml
parity_case "a qa caller mapped to a dev secret" "must be a secrets.<NAME> ending in _QA" 's/secrets\.AWS_PLAN_ROLE_ARN_QA/secrets.AWS_PLAN_ROLE_ARN_DEV/' .github/workflows/terraform-iac.yml
parity_case "a qa caller mapped to an unsuffixed secret" "must be a secrets.<NAME> ending in _QA" 's/secrets\.ALB_INGRESS_CIDRS_QA/secrets.ALB_INGRESS_CIDRS/' .github/workflows/terraform-iac.yml
# shellcheck disable=SC2016  # the sed pattern is YAML text
parity_case "a qa caller mapped to a literal" "must be a secrets.<NAME> ending in _QA" 's/\${{ secrets\.AWS_ACCOUNT_ID_QA }}/123/' .github/workflows/terraform-iac.yml
parity_case "a mismatched env line" "must have exactly one line env = \"qa\"" 's/^env  *= "qa"/env = "dev"/' infra/terraform/envs/qa/terraform.tfvars
parity_case "a duplicate CIDR" "used by more than one env" 's#10\.50\.0\.0/16#10.40.0.0/16#' infra/terraform/envs/qa/terraform.tfvars
parity_case "a wrong backend key" "backend.tf key must be envs/qa/terraform.tfstate" 's#envs/qa/terraform#envs/dev/terraform#' infra/terraform/envs/qa/backend.tf
parity_case "a changed main.tf" "main.tf differs from envs/dev" 's/^module "app_ecs" {/module "app_ecs" { # drift/' infra/terraform/envs/qa/main.tf
parity_case "a changed backend setting" "backend.tf differs from envs/dev" 's/encrypt      = true/encrypt      = false/' infra/terraform/envs/qa/backend.tf
parity_case "a changed README" "README.md differs from envs/dev" 's/^## Run$/## Run it/' infra/terraform/envs/qa/README.md
p="$tmp/pc-missing-example"
cp -R "$base" "$p"
rm "$p/infra/terraform/bootstrap/accounts/qa.tfvars.example"
expect_fail "parity: a missing account example" "missing infra/terraform/bootstrap/accounts/qa.tfvars.example" "$ROOT/scripts/guard/env-parity.sh" "$p"
rm "$base/infra/terraform/envs/qa/tests/envs.tftest.hcl"
expect_fail "parity: a missing file" "missing tests/envs.tftest.hcl" "$ROOT/scripts/guard/env-parity.sh" "$base"
# Allowed differences: a staged upgrade (versions.tf, lock file) and the generated docs block.
p="$tmp/pc-allowed"
parity_base "$p"
sedi 's/~> 6\.70/~> 6.71/' "$p/infra/terraform/envs/qa/versions.tf"
printf '# staged provider upgrade\n' >>"$p/infra/terraform/envs/qa/.terraform.lock.hcl"
sedi 's/^| aws | ~> 6.70 |$/| aws | ~> 6.71 |/' "$p/infra/terraform/envs/qa/README.md"
parity "$p" >/dev/null 2>&1 || die "selftest: the parity guard rejected a staged upgrade (versions.tf, lock file)"
ok "env parity guard: a clone passes; every drift fixture fails with its message; a staged upgrade passes"
# The real tree passes.
"$ROOT/scripts/guard/env-parity.sh"
